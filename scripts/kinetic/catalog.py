"""Deterministic helpers for the repo catalog: the catalog_dir setting, reading
and writing catalog files, merging an approved change file, the index and lint.
The judgment (what a deliverable teaches) lives in skills/catalog-refresh."""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

from kinetic import config
from kinetic.discover import _real, _write

SETTINGS = Path.home() / ".config/kinetic/settings.json"
LAYOUT = ("index.md", "terms.md", "repos", "recipes", "ledger.json")


class CatalogError(ValueError):
    pass


# --- documents: Markdown with a JSON frontmatter block -----------------------

def read_doc(p: Path) -> tuple:
    p = Path(p)
    lines = p.read_text().split("\n")
    if not lines or lines[0].strip() != "---":
        raise CatalogError(f"{p}:1: missing opening '---'")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        raise CatalogError(f"{p}:1: missing closing '---'")
    try:
        meta = json.loads("\n".join(lines[1:end]))
    except ValueError as e:
        line = 1 + getattr(e, "lineno", 1)
        raise CatalogError(f"{p}:{line}: bad frontmatter JSON: {e}")
    if not isinstance(meta, dict):
        raise CatalogError(f"{p}:2: frontmatter must be a JSON object")
    return meta, "\n".join(lines[end + 1:])


def write_doc(p: Path, meta: dict, body: str) -> None:
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text("---\n" + json.dumps(meta, indent=2) + "\n---\n" + body)
    os.replace(tmp, p)


def render_terms(terms: dict) -> str:
    out = ["# Terms", "", "| Term | Meaning | Synonyms | Avoid |", "|---|---|---|---|"]
    for t in sorted(terms):
        e = terms[t]
        out.append(f"| {t} | {e.get('meaning', '')} | {', '.join(e.get('synonyms', []))} "
                   f"| {', '.join(e.get('avoid', []))} |")
    return "\n".join(out) + "\n"


def strength(seen: int, of: int) -> str:
    if seen == 1:
        return "seen once"
    if seen == of:
        return "always"
    if 2 * seen >= of:
        return "usually"
    return "sometimes"


def recipe_repos(meta: dict) -> list:
    """[(repo, seen, of)] ordered by seen descending, then name."""
    sources = meta.get("sources", [])
    seen = {}
    for s in sources:
        for r in s.get("repos", []):
            seen[r] = seen.get(r, 0) + 1
    for r in meta.get("what_for", {}):
        seen.setdefault(r, 0)
    return sorted(((r, n, len(sources)) for r, n in seen.items()), key=lambda x: (-x[1], x[0]))


def render_recipe(meta: dict) -> str:
    out = [f"# {meta.get('title', '')}", "", f"**When to use:** {meta.get('when', '')}", ""]
    params = meta.get("parameters", [])
    if params:
        out.append("**Parameters:** " + "; ".join(
            f"`<{p['name']}>`: {p.get('meaning', '')}"
            + (f" (e.g. {', '.join(p['examples'])})" if p.get("examples") else "") for p in params))
        out.append("")
    for repo, n, of in recipe_repos(meta):
        out.append(f"## {repo} ({strength(n, of) if n else 'not seen'}, {n} of {of})")
        out.extend(f"- {line}" for line in meta.get("what_for", {}).get(repo, []))
        out.append("")
    return "\n".join(out)


def _top_terms(terms: dict, limit: int = 5) -> list:
    return sorted(((t, len(k)) for t, k in terms.items()), key=lambda x: (-x[1], x[0]))[:limit]


def render_repo(meta: dict) -> str:
    out = [f"# {meta.get('repo', '')}", ""]
    if meta.get("owns"):
        out += [meta["owns"], ""]
    out += [f"- {t} ({n})" for t, n in _top_terms(meta.get("terms", {}), limit=10**6)]
    return "\n".join(out) + "\n"


def render_index(cat: dict) -> str:
    out = ["# Catalog index", "", "Generated by `kinetic catalog index`; do not edit.", "", "## Recipes", ""]
    for slug in sorted(cat.get("recipes", {})):
        meta, _ = cat["recipes"][slug]
        repos = ", ".join(f"{r} ({strength(n, of)})" for r, n, of in recipe_repos(meta) if n)
        out.append(f"- {slug} — {meta.get('title', '')} — {meta.get('when', '')} — {repos}")
    out += ["", "## Repos", ""]
    for repo in sorted(cat.get("repos", {})):
        terms = ", ".join(f"{t} ({n})" for t, n in _top_terms(cat["repos"][repo].get("terms", {})))
        out.append(f"- {repo} — {terms}")
    return "\n".join(out) + "\n"


def load(d: Path) -> dict:
    """Read the whole catalog. Raises CatalogError on the first broken file."""
    d = Path(d)
    cat = {"terms": {}, "repos": {}, "recipes": {}, "ledger": {}}
    if (d / "terms.md").is_file():
        cat["terms"] = read_doc(d / "terms.md")[0].get("terms", {})
    for p in sorted((d / "repos").glob("*.md")):
        cat["repos"][p.stem] = read_doc(p)[0]
    for p in sorted((d / "recipes").glob("*.md")):
        cat["recipes"][p.stem] = read_doc(p)
    try:
        cat["ledger"] = config._load(d / "ledger.json")
    except config.ConfigError as e:
        raise CatalogError(str(e))
    return cat


def ledger_lookup(d, keys: list) -> dict:
    ledger = config._load(Path(d) / "ledger.json")
    return {k: dict(ledger[k], cataloged=True) if k in ledger else {"cataloged": False} for k in keys}


def reindex(d) -> dict:
    """Re-render recipe, repo and terms bodies from their frontmatter, then index.md."""
    d = Path(d)
    cat = load(d)
    written = []
    for slug, (meta, _) in cat["recipes"].items():
        write_doc(d / "recipes" / f"{slug}.md", meta, render_recipe(meta))
        written.append(f"recipes/{slug}.md")
    for repo, meta in cat["repos"].items():
        write_doc(d / "repos" / f"{repo}.md", meta, render_repo(meta))
        written.append(f"repos/{repo}.md")
    write_doc(d / "terms.md", {"terms": cat["terms"]}, render_terms(cat["terms"]))
    (d / "index.md").write_text(render_index(cat))
    return {"written": written + ["terms.md", "index.md"]}


def lint(d) -> list:
    d = Path(d)
    problems = []
    docs = {}
    for p in [d / "terms.md"] + sorted((d / "repos").glob("*.md")) + sorted((d / "recipes").glob("*.md")):
        if not p.is_file():
            continue
        try:
            docs[p] = read_doc(p)
        except CatalogError as e:
            problems.append(str(e))
    terms = docs.get(d / "terms.md", ({}, ""))[0].get("terms", {})
    for p, (meta, body) in docs.items():
        if p.parent.name == "repos":
            used = meta.get("terms", {})
        elif p.parent.name == "recipes":
            used = meta.get("terms", [])
            if body != render_recipe(meta):
                problems.append(f"{p}: body does not match its frontmatter (run kinetic catalog index)")
        else:
            continue
        for t in used:
            if t not in terms:
                problems.append(f"{p}: term '{t}' is not in terms.md")
    try:
        config._load(d / "ledger.json")
    except config.ConfigError as e:
        problems.append(str(e))
    return problems


# --- setting -----------------------------------------------------------------

def show(path=None):
    data = config._load(Path(path or SETTINGS))
    v = data.get("catalog_dir")
    return v if isinstance(v, str) and v else None


def is_catalog(d: str) -> bool:
    return os.path.isfile(os.path.join(d, "index.md")) and os.path.isdir(os.path.join(d, "recipes"))


def init_layout(d: Path) -> list:
    d = Path(d)
    d.mkdir(parents=True, exist_ok=True)
    created = []
    for name in LAYOUT:
        p = d / name
        if p.exists():
            continue
        if name in ("repos", "recipes"):
            p.mkdir()
        elif name == "ledger.json":
            _write(p, {})
        elif name == "terms.md":
            write_doc(p, {"terms": {}}, render_terms({}))
        else:
            p.write_text(render_index({}))
        created.append(name)
    return created


def set_dir(d: str, create: bool = False, path=None) -> dict:
    path = Path(path or SETTINGS)
    data = config._load(path)  # raises on bad JSON before anything is written
    real = _real(d)
    if not os.path.isdir(real) and not create:
        raise ValueError(f"not a directory: {d}")
    created = init_layout(Path(real)) if create else []
    data["catalog_dir"] = real
    _write(path, data)
    return {"catalog_dir": real, "created": created}


def _toplevel(cwd: str):
    try:
        r = subprocess.run(["git", "-C", cwd, "rev-parse", "--show-toplevel"],
                           capture_output=True, text=True)
    except OSError:
        return None
    return _real(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip() else None


def detect(cwd: str, path=None) -> dict:
    saved = show(path)
    candidates = []
    if saved:
        candidates.append({"path": saved, "reason": "saved"})
    cur = _real(cwd)
    top = _toplevel(cur) or cur
    while True:
        if is_catalog(cur) and cur != saved:
            candidates.append({"path": cur, "reason": "catalog at or above the current folder"})
            break
        if cur == top or os.path.dirname(cur) == cur:
            break
        cur = os.path.dirname(cur)
    return {"existing_config": saved, "candidates": candidates,
            "recommendation": candidates[0]["path"] if candidates else None}


# --- CLI ---------------------------------------------------------------------

def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="kinetic.catalog")
    sub = p.add_subparsers(dest="cmd", required=True)
    sp = sub.add_parser("detect")
    sp.add_argument("--cwd", default=os.getcwd())
    sp = sub.add_parser("set")
    sp.add_argument("--dir", required=True)
    sp.add_argument("--create", action="store_true")
    sub.add_parser("show")
    sp = sub.add_parser("ledger")
    sp.add_argument("--keys", action="extend", nargs="+", required=True)
    sub.add_parser("index")
    sub.add_parser("lint")
    a = p.parse_args(argv)
    try:
        if a.cmd in ("ledger", "index", "lint"):
            d = show(SETTINGS)
            if not d:
                print("no catalog folder set; run /kinetic:catalog-setup", file=sys.stderr)
                return 1
            if a.cmd == "ledger":
                out = ledger_lookup(d, a.keys)
            elif a.cmd == "index":
                out = reindex(d)
            else:
                problems = lint(d)
                print(json.dumps({"problems": problems}))
                return 1 if problems else 0
        elif a.cmd == "detect":
            out = detect(a.cwd, SETTINGS)
        elif a.cmd == "set":
            out = set_dir(a.dir, a.create, SETTINGS)
        else:
            out = show(SETTINGS)
            print(json.dumps(out))
            return 0 if out else 1
    except (ValueError, OSError, config.ConfigError) as e:
        print(str(e), file=sys.stderr)
        return 1
    print(json.dumps(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
